#!/usr/bin/env node
/**
 * Every measured number on a live surface must name the tool that produced it.
 *
 * WHY THIS EXISTS. Three separate claims shipped in 14.0.0-rc.1 that were not
 * merely stale but ungeneratable — no tool in the repo produced them, so
 * nothing could ever have caught them drifting:
 *
 *   - "Core publishable (gzipped) 25.64KB" / "Total ecosystem 36.32KB" — from a
 *     v9-era methodology that no longer exists. Deleted; not re-derivable.
 *   - "Performance targets (Sept 2025)", four latency figures. Re-measured:
 *     every one was 10x-1000x larger than reality, and "operation" was never
 *     defined, so the claim could be neither verified nor falsified.
 *   - Bundle sizes on five surfaces. The two AI-priming files disagreed with
 *     EACH OTHER — 5.70KB vs 5.46KB for the same bare tree — which is what
 *     "never verified" looks like when you finally check.
 *
 * `check-release-claims.mjs` gates that every SYMBOL reaches every surface.
 * Nothing gated a NUMBER. That gap is why all three survived review.
 *
 * THE RULE. A measurement-shaped figure (KB, ms, µs, ns, `12x`, `40%`) in prose
 * on a live surface must sit in a section that names its generator — a
 * `tools/…` or `scripts/…` path, an `npm run …` script, or an explicit
 * `<!-- measured: … -->` marker. Otherwise it must be listed in EXEMPT with a
 * reason. An undocumented decline is exactly what this gate exists to catch.
 *
 * Section-level, not per-number, because that is the idiom the docs already
 * use ("Reproduce with `node tools/check-bundle-budget.mjs`") and because
 * per-number markers in prose are unreadable, and an unreadable convention gets
 * abandoned.
 *
 *   node tools/check-numeric-claims.mjs
 *   node tools/check-numeric-claims.mjs --list       # every claim it can see
 *   node tools/check-numeric-claims.mjs --self-test  # prove it can fail
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, relative, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Surfaces that describe the CURRENT library to a reader who will act on it.
 *
 * Deliberately excludes `docs/rfcs`, `docs/research`, `docs/archive`,
 * `docs/audits` and `CHANGELOG.md`. Those are point-in-time records: an RFC
 * that measured 9.17KB in June is not wrong today, it is minutes. Rewriting
 * them to match current reality would destroy the thing they are for.
 */
const SURFACES = [
  'README.md',
  // Primes Cursor/Copilot code generation, so a wrong number here becomes wrong
  // numbers in other people's repositories. It was outside this scan entirely
  // until August 2026, and was carrying a bundle table for `@signaltree/enterprise`
  // — a package deleted in 14.0.0 — plus a core size of 15KB against a real 5.79.
  '.cursorrules',
  'AGENTS.md',
  'docs/overview.md',
  'apps/demo/public/llms.txt',
  'apps/demo/public/llms-full.txt',
  ...expandDir('packages', (d) => join('packages', d, 'README.md')),
  ...expandDir('docs/compare', null, 'docs/compare'),
  ...expandDir('docs/performance', null, 'docs/performance'),
  // Added when a new guide carrying measured figures turned out not to be
  // scanned at all. Widening it surfaced 27 pre-existing ungenerated figures
  // across six other guides — a whole surface directory nothing was checking.
  // The backlog went 144 -> 171 and that is the honest number: a larger honest
  // backlog beats a smaller dishonest one, and the ratchet stops it growing.
  ...expandDir('docs/guides', null, 'docs/guides'),
];

function expandDir(dir, mapper, listDir) {
  const abs = join(ROOT, dir);
  if (!existsSync(abs)) return [];
  if (listDir) {
    return readdirSync(abs)
      .filter((f) => f.endsWith('.md'))
      .map((f) => join(listDir, f));
  }
  return readdirSync(abs, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => mapper(e.name))
    .filter((f) => existsSync(join(ROOT, f)));
}

/**
 * A number that asserts a measurement. Narrow on purpose: version numbers,
 * Angular versions, years, counts of things and line references are NOT claims
 * about performance or size, and a gate that flags them gets switched off.
 */
const CLAIM =
  /(\d+(?:\.\d+)?)\s?(KB|MB|kB|ms|µs|us|ns)\b|\b(\d+(?:\.\d+)?)x\b/g;

/** A section names its generator if it mentions one of these. */
const PROVENANCE =
  /(tools|scripts)\/[\w.-]+\.(mjs|js|cjs|ts)|npm run [\w:-]+|<!--\s*measured:/;

/**
 * Claims that legitimately have no generator. Every entry states WHY, because a
 * silent exemption list is how a gate becomes decoration.
 */
const EXEMPT = [
  {
    match: /rxjs|NgRx|SignalStore|Elf|elf|NgXs|Akita|raw-signals/,
    reason:
      'cross-library figure — generated by tools/measure-bundle-sizes.mjs and ' +
      'tools/size-compare.mjs, but usually quoted mid-sentence in a comparison ' +
      'whose section names neither. Covered by those tools, not by prose.',
  },
  {
    match: /Angular|TypeScript|Node|Chrome|Firefox|Safari|Edge/,
    reason:
      'a platform version, not a measurement. version-claims gates these.',
  },
  {
    match: /updateOptimized|@signaltree\/enterprise|enterprise` is no longer/,
    reason:
      'measured against @signaltree/enterprise before it was removed in ' +
      '14.0.0. The package is unpublished and imports symbols that moved to ' +
      '/authoring, so the benchmark cannot be re-run and NO generator can ' +
      'back these — they are the historical justification for a removal, not ' +
      'a live claim. Kept because deleting the numbers would leave "we removed ' +
      'it because it was slower" with nothing behind it. Context: ' +
      'docs/archive/BENCHMARK_ANALYSIS-enterprise-era.md.',
  },
  {
    match: /debounceMs|default(s to)? \d+ ?ms|\d+ ?ms poll|updateTime:|Warn if updates take/,
    reason:
      'a documented default or a configured threshold, not a measurement. No ' +
      'generator can produce it because nothing measured it — the value IS ' +
      'the contract, and changing it changes behaviour rather than correcting ' +
      'a figure. Gating these would train readers to add a fake citation to a ' +
      'constant.',
  },
];

const files = SURFACES.filter((f) => existsSync(join(ROOT, f)));
const claims = [];

for (const file of files) {
  const text = readFileSync(join(ROOT, file), 'utf8');
  const lines = text.split('\n');

  // Section boundaries: a claim inherits provenance from its nearest heading
  // block. Fenced code is skipped — a sample showing `0.27ms` is illustrating
  // an API, not publishing a measurement.
  let sectionStart = 0;
  let inFence = false;
  const sectionOf = [];
  for (let i = 0; i < lines.length; i++) {
    if (/^\s*```/.test(lines[i])) inFence = !inFence;
    if (!inFence && /^#{1,6}\s/.test(lines[i])) sectionStart = i;
    sectionOf[i] = inFence ? -1 : sectionStart;
  }

  const sectionText = new Map();
  const sectionBodyFrom = (start) => {
    if (sectionText.has(start)) return sectionText.get(start);
    let end = start + 1;
    while (end < lines.length && !/^#{1,6}\s/.test(lines[end])) end++;
    const body = lines.slice(start, end).join('\n');
    sectionText.set(start, body);
    return body;
  };

  for (let i = 0; i < lines.length; i++) {
    const start = sectionOf[i];
    if (start === -1) continue; // inside a fence
    const line = lines[i];
    if (/^\s*(>|<!--)/.test(line)) continue; // annotations about removed claims
    CLAIM.lastIndex = 0;
    let m;
    while ((m = CLAIM.exec(line))) {
      const value = m[0].trim();
      const exempt = EXEMPT.find((e) => e.match.test(line));
      const hasProvenance = PROVENANCE.test(sectionBodyFrom(start));
      claims.push({
        file,
        line: i + 1,
        value,
        heading: (lines[start] || '(top of file)').replace(/^#+\s*/, '').trim(),
        ok: hasProvenance || Boolean(exempt),
        exempt: exempt?.reason,
      });
    }
  }
}

const unbacked = claims.filter((c) => !c.ok);

if (process.argv.includes('--list')) {
  for (const c of claims) {
    const mark = c.ok ? (c.exempt ? 'exempt' : 'ok    ') : 'UNBACKED';
    console.log(`  ${mark}  ${c.file}:${c.line}  ${c.value}  — ${c.heading}`);
  }
}

if (process.argv.includes('--self-test')) {
  // The gate must FAIL on a claim with no generator. Proven against a synthetic
  // section rather than by trusting the logic, because the defect this gate
  // exists to catch is precisely "a check that never actually checked".
  const probe = '## Made up\n\nBare tree is 3.21KB and writes take 0.5ms.\n';
  const before = PROVENANCE.test(probe);
  CLAIM.lastIndex = 0;
  const found = [...probe.matchAll(CLAIM)].length;
  const detects = found >= 2 && !before;

  const withTool = probe + '\nReproduce with `node tools/size-report.mjs`.\n';
  const passes = PROVENANCE.test(withTool);

  if (!detects || !passes) {
    console.error(
      `\n❌ self-test FAILED — detects=${detects} passes-with-generator=${passes}`
    );
    process.exit(1);
  }
  console.log(
    `\n✅ self-test: ${found} claims found in an ungenerated section (flagged), ` +
      `and the same section passes once it names a tool.`
  );
  process.exit(0);
}

/**
 * A RATCHET, per file, against a committed baseline — the same shape as
 * `check-lint-budget.mjs`, and for the same reason it gives: 201 of these
 * existed on the day the gate was written, and failing the build on all of them
 * would mean either a mass annotation sweep or a permanently red gate. A red
 * gate teaches people to ignore gates.
 *
 * So: no file may exceed its recorded count. New documentation cannot introduce
 * an ungenerated number; the existing backlog is paid down at whatever pace
 * suits. When a count DROPS, `--update` tightens the baseline, so progress is
 * locked in rather than left as slack for the next regression to spend.
 */
const BASELINE = join(ROOT, 'tools/numeric-claims-baseline.json');

const counts = {};
for (const c of unbacked) counts[c.file] = (counts[c.file] ?? 0) + 1;

const backed = claims.length - unbacked.length;
console.log(
  `\n${claims.length} measured figure(s) across ${files.length} live surface(s); ` +
    `${backed} backed by a named generator or exempt.`
);

if (process.argv.includes('--update')) {
  const sorted = Object.fromEntries(
    Object.entries(counts).sort(([a], [b]) => a.localeCompare(b))
  );
  writeFileSync(BASELINE, JSON.stringify(sorted, null, 2) + '\n');
  console.log(
    `\n✅ baseline written: ${unbacked.length} unbacked across ` +
      `${Object.keys(sorted).length} file(s).\n`
  );
  process.exit(0);
}

if (!existsSync(BASELINE)) {
  console.error(
    `\n❌ No baseline at ${relative(ROOT, BASELINE)}.\n` +
      `   Create it with: node tools/check-numeric-claims.mjs --update\n`
  );
  process.exit(1);
}

const base = JSON.parse(readFileSync(BASELINE, 'utf8'));
const regressions = [];
const improvements = [];
for (const file of new Set([...Object.keys(counts), ...Object.keys(base)])) {
  const now = counts[file] ?? 0;
  const was = base[file] ?? 0;
  if (now > was) regressions.push({ file, now, was });
  else if (now < was) improvements.push({ file, now, was });
}

if (regressions.length) {
  console.error('');
  for (const r of regressions) {
    console.error(`  ❌ ${r.file}  ${r.was} → ${r.now} ungenerated figure(s)`);
    for (const c of unbacked.filter((c) => c.file === r.file)) {
      console.error(
        `       line ${c.line}  ${c.value}  — under "${c.heading}"`
      );
    }
  }
  console.error(
    `\n❌ New published number(s) name no tool that produces them.\n` +
      `   A claim with no generator cannot go stale loudly — it just quietly\n` +
      `   stops being true. Three of those shipped in 14.0.0-rc.1: two size\n` +
      `   rows with a methodology that no longer existed, and a latency table\n` +
      `   whose figures were 10x-1000x wrong.\n\n` +
      `   Fix by either:\n` +
      `     · naming the generator in the section ("Reproduce with \`node tools/x.mjs\`"),\n` +
      `     · adding <!-- measured: how --> next to it, or\n` +
      `     · adding it to EXEMPT in this file WITH A REASON.\n`
  );
  process.exit(1);
}

if (improvements.length) {
  for (const i of improvements) {
    console.log(`  ✓ ${i.file}  ${i.was} → ${i.now}`);
  }
  console.error(
    `\n❌ Backlog shrank — tighten the baseline so the win is locked in:\n` +
      `       node tools/check-numeric-claims.mjs --update\n`
  );
  process.exit(1);
}

console.log(
  `✅ no new ungenerated figures. Backlog: ${unbacked.length} across ` +
    `${Object.keys(counts).length} file(s), held flat by the ratchet.\n`
);
